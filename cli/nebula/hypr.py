import json
import os
import re
import sys
import tempfile
from pathlib import Path

from nebula.paths import HOME

HYPR = Path(os.environ.get("XDG_CONFIG_HOME") or HOME / ".config") / "hypr"
MAIN = HYPR / "hyprland.lua"
AREAS = ("displays", "windows", "input", "binds")
HEADER = "-- Generated by Nebula › Settings ({area}). Changes here are overwritten.\n"


def begin(area: str) -> str:
    return f"-- >>> Nebula: {area} >>>"


def end(area: str) -> str:
    return f"-- <<< Nebula: {area} <<<"


def nebula_file(area: str) -> Path:
    return HYPR / "nebula" / f"{area}.lua"


def module_of(path: Path) -> str:
    try:
        rel = path.resolve().relative_to(HYPR.resolve())
    except ValueError:
        return ""
    return ".".join(rel.with_suffix("").parts)


def write_atomic(path: Path, text: str) -> None:
    target = path.resolve() if path.is_symlink() else path
    try:
        if target.read_text() == text:
            return
    except OSError:
        pass
    target.parent.mkdir(parents=True, exist_ok=True)
    mode = target.stat().st_mode & 0o7777 if target.exists() else 0o644
    fd, tmp = tempfile.mkstemp(dir=target.parent, prefix="." + target.name + ".")
    try:
        with os.fdopen(fd, "w") as f:
            f.write(text)
        os.chmod(tmp, mode)
        os.replace(tmp, target)
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


def splice(text: str, area: str, body: str) -> str:
    pattern = re.compile(r"\n?" + re.escape(begin(area)) + r".*?" + re.escape(end(area)) + r"\n?", re.S)
    stripped = pattern.sub("\n", text) if pattern.search(text) else text
    if body.strip() == "":
        return stripped.rstrip("\n") + "\n" if stripped.strip() else ""
    block = f"{begin(area)}\n-- Written by Nebula › Settings. Edit outside this block; Nebula rewrites it.\n{body.rstrip()}\n{end(area)}\n"
    base = stripped.rstrip("\n")
    return (base + "\n\n" if base else "") + block


def all_lua_text() -> str:
    out = []
    for p in HYPR.rglob("*.lua"):
        try:
            out.append(p.read_text())
        except OSError:
            pass
    return "\n".join(out)


def is_required(module: str) -> bool:
    if not module:
        return False
    pat = re.compile(r"require\s*\(?\s*[\"']" + re.escape(module) + r"[\"']")
    return bool(pat.search(all_lua_text()))


def ensure_require(module: str) -> bool:
    if is_required(module):
        return False
    text = MAIN.read_text() if MAIN.exists() else ""
    base = text.rstrip("\n")
    last = base.rsplit("\n", 1)[-1].strip() if base else ""
    sep = "" if not base else "\n" if last.startswith("require") else "\n\n"
    write_atomic(MAIN, base + sep + f'require("{module}")\n')
    return True


def status(path: Path) -> dict:
    module = module_of(path)
    return {"file": str(path), "module": module, "exists": path.exists(),
            "required": path == MAIN.resolve() or path == MAIN or is_required(module)}


def cmd_write(area: str, mode: str, file: str) -> int:
    body = sys.stdin.read()
    if mode == "nebula":
        path = nebula_file(area)
        write_atomic(path, HEADER.format(area=area) + ("\n" + body.rstrip() + "\n" if body.strip() else ""))
        ensure_require(module_of(path))
    else:
        path = Path(os.path.expanduser(file))
        text = path.read_text() if path.exists() else ""
        write_atomic(path, splice(text, area, body))
    print(json.dumps(status(path)))
    return 0


def cmd_remove(area: str, file: str) -> int:
    path = Path(os.path.expanduser(file))
    if path.exists():
        write_atomic(path, splice(path.read_text(), area, ""))
    print(json.dumps(status(path)))
    return 0


def cmd_status(file: str) -> int:
    print(json.dumps(status(Path(os.path.expanduser(file)))))
    return 0


def cmd_require(file: str) -> int:
    path = Path(os.path.expanduser(file))
    module = module_of(path)
    if module:
        ensure_require(module)
    print(json.dumps(status(path)))
    return 0


def cmd_retire_legacy() -> int:
    legacy = HYPR / "nebula" / "settings.lua"
    if legacy.exists():
        write_atomic(legacy, "-- Nebula now writes displays.lua, windows.lua, input.lua and binds.lua instead.\n")
    print(json.dumps({"retired": legacy.exists()}))
    return 0


def main(argv=None) -> None:
    a = list(sys.argv[1:] if argv is None else argv)
    usage = "usage: nebula hypr write AREA nebula|own [FILE] < body | remove AREA FILE | status FILE | require FILE | retire-legacy"
    if not a:
        print(usage, file=sys.stderr)
        sys.exit(2)
    cmd = a[0]
    if cmd == "write" and len(a) >= 3 and a[1] in AREAS and a[2] in ("nebula", "own") and (a[2] == "nebula" or len(a) >= 4):
        sys.exit(cmd_write(a[1], a[2], a[3] if len(a) >= 4 else ""))
    if cmd == "remove" and len(a) == 3 and a[1] in AREAS:
        sys.exit(cmd_remove(a[1], a[2]))
    if cmd == "status" and len(a) == 2:
        sys.exit(cmd_status(a[1]))
    if cmd == "require" and len(a) == 2:
        sys.exit(cmd_require(a[1]))
    if cmd == "retire-legacy":
        sys.exit(cmd_retire_legacy())
    print(usage, file=sys.stderr)
    sys.exit(2)


if __name__ == "__main__":
    main()
